// Bundles src/client.ts (with diff.ts and msgpack.ts) into one browser ES module and writes it to
// src/client-bundle.ts, which the rooms plugin serves at GET /rooms/_client.js. Users never run
// this: the bundle is committed. Re-run it after changing the client:
//
//   bun packages/realtime/scripts/build-client.ts
//
// test/client-bundle.test.ts fails while the committed bundle is out of date.

const here = new URL(".", import.meta.url);

export async function buildClient(): Promise<{ js: string; hash: string }> {
  const r = await Bun.build({ entrypoints: [new URL("../src/client.ts", here).pathname.replace(/^\/([A-Za-z]:)/, "$1")], target: "browser", format: "esm", minify: true });
  if (!r.success) throw new Error(r.logs.map(String).join("\n"));
  const js = await r.outputs[0].text();
  if (/node:/.test(js)) throw new Error("the browser client must not import node: modules");
  const digest = new Uint8Array(await crypto.subtle.digest("SHA-256", new TextEncoder().encode(js)));
  const hash = [...digest.slice(0, 8)].map((b) => b.toString(16).padStart(2, "0")).join("");
  return { js, hash };
}

if (import.meta.main) {
  const { js, hash } = await buildClient();
  const out = `// Generated by scripts/build-client.ts from src/client.ts. Do not edit by hand.\n// Served by rooms() at GET /rooms/_client.js and /rooms/_client/<hash>.js.\n\nexport const CLIENT_JS = ${JSON.stringify(js)};\n\nexport const CLIENT_JS_HASH = ${JSON.stringify(hash)};\n`;
  await Bun.write(new URL("../src/client-bundle.ts", here), out);
  console.log(`wrote src/client-bundle.ts (${js.length} bytes, ${hash})`);
}
