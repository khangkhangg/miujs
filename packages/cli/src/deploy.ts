// `miu deploy <target>`: cloudflare (wrangler.toml), fly, railway, render, vps, binary, deno-deploy.
// Every target writes its files first; --dry-run stops there and prints the next commands.

import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { BUNX, CliError, findEntry, loadAppModule, str, walk, writeFile, type AppLike, type CliIO, type Flags, type Runner } from "./util.ts";

export const DEPLOY_TARGETS = ["cloudflare", "fly", "railway", "render", "vps", "binary", "deno-deploy"] as const;

// ---------------------------------------------------------------------------------------------
// wrangler.toml

export function wranglerToml(info: any, main: string, date = new Date().toISOString().slice(0, 10)): string {
  const cf = info.cloudflare ?? {};
  const queueName = (b: string) => b.toLowerCase().replace(/_/g, "-");
  const parts: string[] = [
    `# Generated by \`miu deploy cloudflare\`. Re-run it after adding plugins.`,
    `name = "${info.name}"`,
    `main = "${main}"`,
    `compatibility_date = "${date}"`,
  ];
  for (const b of cf.kv ?? []) parts.push(`\n[[kv_namespaces]]\nbinding = "${b}"`);
  for (const b of cf.d1 ?? []) parts.push(`\n[[d1_databases]]\nbinding = "${b}"\ndatabase_name = "${queueName(b)}"`);
  for (const b of cf.r2 ?? []) parts.push(`\n[[r2_buckets]]\nbinding = "${b}"\nbucket_name = "${queueName(b)}"`);
  for (const b of cf.queues?.producers ?? []) parts.push(`\n[[queues.producers]]\nbinding = "${b}"\nqueue = "${queueName(b)}"`);
  for (const b of cf.queues?.consumers ?? []) parts.push(`\n[[queues.consumers]]\nqueue = "${queueName(b)}"`);
  const dos = cf.durableObjects ?? [];
  for (const d of dos) parts.push(`\n[[durable_objects.bindings]]\nname = "${d.binding}"\nclass_name = "${d.className}"`);
  if (dos.length) {
    parts.push(`\n[[migrations]]\ntag = "v1"\nnew_sqlite_classes = [${dos.map((d: { className: string }) => `"${d.className}"`).join(", ")}]`);
  }
  if (cf.crons?.length) parts.push(`\n[triggers]\ncrons = [${cf.crons.map((c: string) => `"${c}"`).join(", ")}]`);
  if (cf.assets) {
    const a = cf.assets;
    let block = `\n[assets]\ndirectory = "${a.directory}"\nbinding = "${a.binding ?? "ASSETS"}"`;
    if (a.notFoundHandling) block += `\nnot_found_handling = "${a.notFoundHandling}"`;
    if (a.htmlHandling) block += `\nhtml_handling = "${a.htmlHandling}"`;
    if (a.runWorkerFirst !== undefined) {
      block += `\nrun_worker_first = ${Array.isArray(a.runWorkerFirst) ? `[${a.runWorkerFirst.map((p: string) => `"${p}"`).join(", ")}]` : a.runWorkerFirst}`;
    }
    parts.push(block);
  }
  if (cf.ai) parts.push(`\n[ai]\nbinding = "${cf.ai.binding}"`);
  for (const v of cf.vectorize ?? []) parts.push(`\n[[vectorize]]\nbinding = "${v.binding}"\nindex_name = "${v.indexName}"`);
  for (const w of cf.workflows ?? []) parts.push(`\n[[workflows]]\nname = "${w.name}"\nbinding = "${w.binding}"\nclass_name = "${w.className}"`);
  for (const r of cf.ratelimits ?? []) {
    // namespace_id must be a positive integer unique within the account; derive a stable one from the binding name.
    const ns = r.namespaceId ?? String(1000 + [...String(r.binding)].reduce((h, c) => (h * 31 + c.charCodeAt(0)) % 9000, 7));
    parts.push(`\n[[ratelimits]]\nname = "${r.binding}"\nnamespace_id = "${ns}"\n\n  [ratelimits.simple]\n  limit = ${r.limit}\n  period = ${r.period}`);
  }
  return parts.join("\n") + "\n";
}

// ---------------------------------------------------------------------------------------------
// secrets and env vars the app reads

const NOT_CONFIG = new Set(["MIU_ENV", "NODE_ENV", "MIU_TARGET", "PORT", "HOST", "HOSTNAME", "TZ", "PATH", "HOME"]);
const KNOWN_SECRETS = ["SESSION_SECRET", "AUDIT_HMAC_KEY", "FILES_SECRET", "ANTHROPIC_API_KEY"];
const PLUGIN_SECRETS: Record<string, string[]> = { audit: ["AUDIT_HMAC_KEY"], ai: ["ANTHROPIC_API_KEY"] };
const SECRET_NAME = /SECRET|KEY|TOKEN|PASSWORD|PASSWD|PRIVATE|CREDENTIAL|DSN/;

function bindingNames(cf: any): Set<string> {
  const names = new Set<string>();
  const add = (v: unknown) => typeof v === "string" && names.add(v);
  for (const k of ["kv", "d1", "r2"]) for (const b of cf?.[k] ?? []) add(b);
  for (const b of cf?.queues?.producers ?? []) add(b);
  for (const d of cf?.durableObjects ?? []) add(d.binding);
  for (const w of cf?.workflows ?? []) add(w.binding);
  for (const r of cf?.ratelimits ?? []) add(r.binding);
  for (const v of cf?.vectorize ?? []) add(v.binding);
  add(cf?.ai?.binding);
  add(cf?.assets?.binding ?? (cf?.assets ? "ASSETS" : undefined));
  return names;
}

/**
 * Env names the app reads: `env.X` / `env["X"]` in its source (tests skipped), names the plugins
 * report in `inspect()` (e.g. session's "env.SESSION_SECRET"), and well-known battery secrets.
 * Split into secrets (names with SECRET/KEY/TOKEN/...) and plain vars; Cloudflare bindings excluded.
 */
export function appEnv(cwd: string, info: any): { secrets: string[]; vars: string[] } {
  const found = new Set<string>();
  const scan = (text: string) => {
    for (const m of text.matchAll(/\benv\??\.([A-Z][A-Z0-9_]*)\b/g)) found.add(m[1]);
    for (const m of text.matchAll(/\benv\??\.?\[\s*["'`]([A-Z][A-Z0-9_]*)["'`]\s*\]/g)) found.add(m[1]);
  };
  for (const file of walk(cwd, /\.(ts|tsx|js|mjs|jsx)$/)) {
    const rel = relative(cwd, file).replace(/\\/g, "/");
    if (/(^|\/)(test|tests|__tests__)\//.test(rel) || /\.(test|spec)\.[tj]sx?$/.test(rel)) continue;
    const text = readFileSync(file, "utf8");
    scan(text);
    for (const k of KNOWN_SECRETS) if (new RegExp(`\\b${k}\\b`).test(text)) found.add(k);
  }
  scan(JSON.stringify(info?.plugins ?? []));
  for (const p of info?.plugins ?? []) for (const k of PLUGIN_SECRETS[p?.name] ?? []) found.add(k);
  const bindings = bindingNames(info?.cloudflare);
  const names = [...found].filter((n) => !NOT_CONFIG.has(n) && !bindings.has(n)).sort();
  return { secrets: names.filter((n) => SECRET_NAME.test(n)), vars: names.filter((n) => !SECRET_NAME.test(n)) };
}

// ---------------------------------------------------------------------------------------------
// files

interface Project {
  cwd: string;
  name: string;
  entry: string;
  /** Entry relative to cwd, with forward slashes. */
  entryRel: string;
  app: AppLike;
  mod: Record<string, unknown>;
  info: any;
  env: { secrets: string[]; vars: string[] };
  port: number;
}

const SKIP_TOP = new Set(["node_modules", "dist", "test", "tests", "__tests__", "docs", "coverage", "deploy", "bench", "examples"]);
const SHIP_FILE = /\.(ts|tsx|js|mjs|cjs|jsx|json|html|css|txt|sql|toml)$/;
const NOT_SHIPPED = new Set(["package.json", "bun.lock", "bun.lockb", "package-lock.json", "railway.json", "deno.json", "fly.toml", "wrangler.toml", "render.yaml"]);

/** Top-level files and folders the app needs at runtime: sources, assets, migrations. Not tests or docs. */
export function shippedPaths(cwd: string): { files: string[]; dirs: string[] } {
  const files: string[] = [];
  const dirs: string[] = [];
  for (const name of readdirSync(cwd).sort()) {
    if (name.startsWith(".")) continue;
    const st = statSync(join(cwd, name));
    if (st.isDirectory()) {
      if (!SKIP_TOP.has(name)) dirs.push(name);
    } else if (SHIP_FILE.test(name) && !NOT_SHIPPED.has(name) && !/\.(test|spec)\.[tj]sx?$/.test(name)) files.push(name);
  }
  return { files, dirs };
}

export function dockerfile(p: Project, target: string): string {
  const { files, dirs } = shippedPaths(p.cwd);
  const lock = existsSync(join(p.cwd, "bun.lock")) ? "bun.lock" : existsSync(join(p.cwd, "bun.lockb")) ? "bun.lockb" : null;
  return [
    `# Generated by \`miu deploy ${target}\`. Re-run with --force after adding top-level folders.`,
    `# Two stages: production dependencies only, then a slim image that runs as the non-root "bun" user.`,
    `FROM oven/bun:1 AS install`,
    `WORKDIR /app`,
    `COPY package.json ${lock ? `${lock} ` : ""}./`,
    `RUN bun install --production${lock ? " --frozen-lockfile" : ""}`,
    ``,
    `FROM oven/bun:1-slim`,
    `WORKDIR /app`,
    `ENV NODE_ENV=production MIU_ENV=production PORT=${p.port}`,
    `COPY --from=install --chown=bun:bun /app/node_modules ./node_modules`,
    `COPY --chown=bun:bun ${["package.json", ...files].join(" ")} ./`,
    ...dirs.map((d) => `COPY --chown=bun:bun ${d} ./${d}`),
    `# Writable folder for SQLite files and uploads (mount a volume here to keep them).`,
    `RUN mkdir -p /app/data && chown bun:bun /app/data`,
    `USER bun`,
    `EXPOSE ${p.port}`,
    `CMD ["bun", "${p.entryRel}"]`,
    ``,
  ].join("\n");
}

const DOCKERIGNORE = ["node_modules", ".git", ".wrangler", ".miu", "dist", "test", "tests", "*.test.ts", "*.sqlite", "*.sqlite-*", ".env", ".env.*", "Dockerfile", ".dockerignore", ""].join("\n");

function flyToml(p: Project, region: string): string {
  return `# Generated by \`miu deploy fly\`.
app = "${p.name}"
primary_region = "${region}"

[build]
  dockerfile = "Dockerfile"

[env]
  MIU_ENV = "production"
  PORT = "${p.port}"

[http_service]
  internal_port = ${p.port}
  force_https = true
  auto_stop_machines = "stop"
  auto_start_machines = true
  min_machines_running = 0
`;
}

function renderYaml(p: Project): string {
  const env = [
    `      - key: MIU_ENV\n        value: production`,
    ...[...p.env.secrets, ...p.env.vars].map((k) => `      - key: ${k}\n        sync: false`),
  ];
  return `# Generated by \`miu deploy render\`. Render Blueprint: Dashboard → New → Blueprint → this repo.
services:
  - type: web
    name: ${p.name}
    runtime: docker
    dockerfilePath: ./Dockerfile
    plan: starter
    envVars:
${env.join("\n")}
`;
}

function vpsUnit(p: Project, user: string): string {
  return `# Generated by \`miu deploy vps\`. Install: /etc/systemd/system/${p.name}.service
[Unit]
Description=${p.name} (MiuJS)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=${user}
WorkingDirectory=/srv/${p.name}
Environment=MIU_ENV=production
Environment=NODE_ENV=production
Environment=PORT=${p.port}
# Secrets (one NAME=value per line, chmod 600): ${[...p.env.secrets, ...p.env.vars].join(", ") || "none detected"}
EnvironmentFile=-/etc/${p.name}.env
ExecStart=/usr/local/bin/bun ${p.entryRel}
Restart=always
RestartSec=2
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=true
PrivateTmp=true
ReadWritePaths=/srv/${p.name}/data

[Install]
WantedBy=multi-user.target
`;
}

function caddyfile(p: Project, domain: string): string {
  return `# Generated by \`miu deploy vps\`. Caddy gets the TLS certificate for ${domain} automatically.
${domain} {
  encode zstd gzip
  reverse_proxy 127.0.0.1:${p.port}
}
`;
}

const SERVER_ENTRY = (entryFromMiu: string) => `// Generated by \`miu deploy binary\`: the entry \`bun build --compile\` turns into one executable.
import app from "${entryFromMiu}";

const server = await app.listen(Number(process.env.PORT ?? 3000));
console.log(\`\${app.name} listening on \${server.url}\`);
`;

