// command

function writeTargetFile(io: CliIO, flags: Flags, rel: string, content: string) {
  const file = join(io.cwd, rel);
  if (existsSync(file) && !flags.force) {
    io.out(`Kept ${rel} (it exists; --force overwrites it)`);
    return;
  }
  writeFile(file, content);
  io.out(`Wrote ${rel}`);
}

async function loadProject(io: CliIO, flags: Flags): Promise<Project> {
  const entry = findEntry(io.cwd, str(flags, "entry"));
  const { app, mod } = await loadAppModule(entry);
  const info = app.inspect();
  const port = Number(str(flags, "port") ?? 3000);
  const name = String(info.name ?? "miu-app").toLowerCase().replace(/[^a-z0-9-]/g, "-");
  return { cwd: io.cwd, name, entry, entryRel: relative(io.cwd, entry).replace(/\\/g, "/"), app, mod, info, env: appEnv(io.cwd, info), port };
}

function printSecrets(io: CliIO, p: Project, setCmd: (name: string) => string, varsNote: string) {
  if (p.env.secrets.length) {
    io.out(`\nSecrets the app reads (set each once):`);
    for (const s of p.env.secrets) io.out(`  ${setCmd(s)}`);
  }
  if (p.env.vars.length) io.out(`\nOther env vars the app reads: ${p.env.vars.join(", ")}. ${varsNote}`);
}

function nextSteps(io: CliIO, lines: string[]) {
  io.out(`\nNext:`);
  for (const l of lines) io.out(`  ${l}`);
}

async function deployCloudflare(io: CliIO, flags: Flags, run: Runner) {
  const entry = findEntry(io.cwd, str(flags, "entry"));
  const out = resolve(io.cwd, str(flags, "out") ?? "wrangler.toml");
  // Build the app as Workers will run it, so plugins pick their Cloudflare defaults
  // (see targetRuntime() in miujs) and declare the bindings they need.
  const previous = process.env.MIU_TARGET;
  process.env.MIU_TARGET = "cloudflare";
  let toml: string;
  let info: any;
  let mod: Record<string, unknown>;
  try {
    const loaded = await loadAppModule(entry);
    info = loaded.app.inspect();
    mod = loaded.mod;
    toml = wranglerToml(info, relative(dirname(out), entry).replace(/\\/g, "/"));
  } finally {
    if (previous === undefined) delete process.env.MIU_TARGET;
    else process.env.MIU_TARGET = previous;
  }
  if (existsSync(out) && !flags.force && !flags["dry-run"]) {
    throw new CliError("MIU_E_CLI_EXISTS", `${out} already exists`, "Re-run with --force to overwrite it, or --dry-run --out other.toml to compare.");
  }
  writeFile(out, toml);
  io.out(`Wrote ${out}`);
  if (flags["dry-run"]) io.out(toml);

  const entryRel = relative(io.cwd, entry).replace(/\\/g, "/");
  for (const d of info.cloudflare?.durableObjects ?? []) {
    if (!(d.className in mod)) {
      io.out(
        `warn  MIU_W_DO_NOT_EXPORTED binding ${d.binding} needs the Durable Object class ${d.className}, but ${entryRel} does not export it. Fix: add \`export const ${d.className} = createRoomDurableObject([...rooms])\` (or your class) to ${entryRel}.`,
      );
    }
  }
  for (const w of info.cloudflare?.workflows ?? []) {
    if (!(w.className in mod)) {
      io.out(`warn  MIU_W_WORKFLOW_NOT_EXPORTED binding ${w.binding} needs the Workflow class ${w.className}, but ${entryRel} does not export it. Fix: add \`export const ${w.className} = createCloudflareWorkflow(...)\` to ${entryRel}.`);
    }
  }
  const env = appEnv(io.cwd, info);
  printSecrets(io, { env } as Project, (s) => `bunx wrangler secret put ${s}`, "Put plain values under [vars] in wrangler.toml.");
  if (flags["dry-run"]) {
    nextSteps(io, ["bunx wrangler login", `bunx wrangler deploy --config ${relative(io.cwd, out).replace(/\\/g, "/") || "wrangler.toml"}`]);
    return 0;
  }
  return (await run([...BUNX(), "wrangler", "deploy", "--config", out], { cwd: io.cwd, inherit: true })).code;
}

export async function cmdDeploy(io: CliIO, positional: string[], flags: Flags, run: Runner) {
  const target = positional[0];
  if (!DEPLOY_TARGETS.includes(target as never)) {
    throw new CliError("MIU_E_CLI_DEPLOY_TARGET", `Unknown deploy target "${target ?? ""}"`, `Use \`miu deploy <target>\` with one of: ${DEPLOY_TARGETS.join(", ")}.`);
  }
  if (target === "cloudflare") return deployCloudflare(io, flags, run);

  const p = await loadProject(io, flags);
  const dry = !!flags["dry-run"];
  const exec = async (cmd: string[]) => (await run(cmd, { cwd: io.cwd, inherit: true })).code;

  switch (target) {
    case "fly": {
      writeTargetFile(io, flags, "Dockerfile", dockerfile(p, "fly"));
      writeTargetFile(io, flags, ".dockerignore", DOCKERIGNORE);
      writeTargetFile(io, flags, "fly.toml", flyToml(p, str(flags, "region") ?? "iad"));
      printSecrets(io, p, (s) => `fly secrets set ${s}=...`, "Set them with `fly secrets set` too, or under [env] in fly.toml.");
      if (dry) {
        nextSteps(io, ["fly launch --no-deploy --copy-config   (first time only)", "fly deploy"]);
        return 0;
      }
      return exec(["flyctl", "deploy"]);
    }
    case "railway": {
      writeTargetFile(io, flags, "Dockerfile", dockerfile(p, "railway"));
      writeTargetFile(io, flags, ".dockerignore", DOCKERIGNORE);
      writeTargetFile(io, flags, "railway.json", JSON.stringify({ $schema: "https://railway.com/railway.schema.json", build: { builder: "DOCKERFILE", dockerfilePath: "Dockerfile" }, deploy: { restartPolicyType: "ON_FAILURE" } }, null, 2) + "\n");
      printSecrets(io, p, (s) => `railway variables --set "${s}=..."`, "Set them with `railway variables --set` too.");
      if (dry) {
        nextSteps(io, ["railway login", "railway init   (first time only)", "railway variables --set MIU_ENV=production", "railway up"]);
        return 0;
      }
      return exec(["railway", "up"]);
    }
    case "render": {
      writeTargetFile(io, flags, "Dockerfile", dockerfile(p, "render"));
      writeTargetFile(io, flags, ".dockerignore", DOCKERIGNORE);
      writeTargetFile(io, flags, "render.yaml", renderYaml(p));
      if (p.env.secrets.length || p.env.vars.length) io.out(`\nrender.yaml lists ${[...p.env.secrets, ...p.env.vars].join(", ")} with sync: false; Render asks for their values when you create the Blueprint.`);
      // Render deploys from your git repository; there is no CLI step to run.
      nextSteps(io, ["git add Dockerfile .dockerignore render.yaml && git commit -m \"Deploy to Render\" && git push", "Render dashboard → New → Blueprint → pick this repository"]);
      return 0;
    }
    case "vps": {
      const host = str(flags, "host") ?? "user@your-server";
      const domain = str(flags, "domain") ?? "example.com";
      const sshUser = host.includes("@") ? host.split("@")[0] : "";
      const user = sshUser && sshUser !== "root" ? sshUser : "miu";
      writeTargetFile(io, flags, `deploy/${p.name}.service`, vpsUnit(p, user));
      writeTargetFile(io, flags, "deploy/Caddyfile", caddyfile(p, domain));
      const dir = `/srv/${p.name}`;
      const secrets = [...p.env.secrets, ...p.env.vars];
      // Printed, never run: these touch a server you own.
      nextSteps(io, [
        `# once, on the server: install Bun system-wide and Caddy, and create ${dir}`,
        `ssh ${host} 'curl -fsSL https://bun.sh/install | sudo BUN_INSTALL=/usr/local bash && sudo mkdir -p ${dir}/data && sudo chown -R ${user} ${dir}'`,
        ...(secrets.length ? [`ssh ${host} 'sudo install -m 600 -o ${user} /dev/null /etc/${p.name}.env'   # then add ${secrets.join(", ")}`] : []),
        `# every deploy:`,
        `rsync -az --delete --exclude node_modules --exclude .git --exclude test --exclude data --exclude '*.sqlite' ./ ${host}:${dir}/`,
        `ssh ${host} 'cd ${dir} && bun install --production && sudo cp deploy/${p.name}.service /etc/systemd/system/ && sudo systemctl daemon-reload && sudo systemctl enable ${p.name} && sudo systemctl restart ${p.name}'`,
        `ssh ${host} 'sudo cp ${dir}/deploy/Caddyfile /etc/caddy/Caddyfile && sudo systemctl reload caddy'`,
      ]);
      return 0;
    }
    case "binary": {
      const out = str(flags, "out") ?? `dist/${p.name}`;
      const serverRel = ".miu/server.ts";
      const importPath = relative(join(io.cwd, ".miu"), p.entry).replace(/\\/g, "/");
      writeFile(join(io.cwd, serverRel), SERVER_ENTRY(importPath.startsWith(".") ? importPath : `./${importPath}`));
      io.out(`Wrote ${serverRel}`);
      const cmd = ["bun", "build", "--compile", serverRel, "--outfile", out];
      if (dry) {
        nextSteps(io, [cmd.join(" "), `PORT=${p.port} MIU_ENV=production ./${out}`]);
        return 0;
      }
      const r = await run([process.execPath, ...cmd.slice(1)], { cwd: io.cwd });
      if (r.code !== 0) throw new CliError("MIU_E_CLI_BUILD_FAILED", `bun build --compile failed: ${(r.stderr || r.stdout).trim().slice(0, 2000)}`, "Fix the errors above; `bun build --compile .miu/server.ts` reproduces them.");
      io.out(`Built ${out}${process.platform === "win32" ? ".exe" : ""}. Run it with PORT=${p.port} MIU_ENV=production.`);
      if (existsSync(join(io.cwd, "public"))) io.out("Note: files read from disk at runtime (e.g. public/) are not embedded; ship them next to the binary.");
      return 0;
    }
    case "deno-deploy": {
      const file = join(io.cwd, "deno.json");
      let config: Record<string, unknown> = {};
      if (existsSync(file)) {
        try {
          config = JSON.parse(readFileSync(file, "utf8"));
        } catch {
          throw new CliError("MIU_E_CLI_DENO_JSON", "deno.json is not valid JSON", "Fix deno.json (or delete it) and re-run.");
        }
      }
      if (config.deploy && !flags.force) io.out("Kept the deploy section of deno.json (--force overwrites it)");
      else {
        config.deploy = { project: p.name, entrypoint: p.entryRel, include: ["."], exclude: ["node_modules", "test", "dist", ".git"] };
        writeFile(file, JSON.stringify(config, null, 2) + "\n");
        io.out("Wrote deno.json (deploy section)");
      }
      const cmd = ["deployctl", "deploy", `--project=${p.name}`, `--entrypoint=${p.entryRel}`, "--prod"];
      printSecrets(io, p, (s) => `${s}: Deno Deploy dashboard → Project → Settings → Environment Variables`, "Set them in the Deno Deploy dashboard as well.");
      if (dry) {
        nextSteps(io, ["deno install -gArf jsr:@deno/deployctl   (first time only)", cmd.join(" ")]);
        return 0;
      }
      return exec(cmd);
    }
  }
  return 0;
}
