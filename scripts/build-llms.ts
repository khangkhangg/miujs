// Generates llms.txt (an index for LLMs, see https://llmstxt.org) and llms-full.txt (the docs in one file).
//
//   bun scripts/build-llms.ts           # write both files
//   bun scripts/build-llms.ts --check   # exit 1 if either is out of date (CI)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, posix } from "node:path";
import { DOCUMENTED_PACKAGES, ROOT, blobUrl, rawUrl } from "./lib/repo.ts";

const read = (p: string) => readFileSync(join(ROOT, p), "utf8").replace(/\r\n/g, "\n");
const npmName = (pkg: string) => (pkg === "miujs" ? "miujs" : `@miujs/${pkg}`);

/** The `> summary` on line 3 of a package README. */
function summary(pkg: string): string {
  const line = read(`packages/${pkg}/README.md`).split("\n")[2] ?? "";
  if (!line.startsWith(">")) throw new Error(`packages/${pkg}/README.md: line 3 must be a "> one-sentence summary"`);
  return line.replace(/^>\s*/, "").trim();
}

export function renderLlmsTxt(): string {
  const pkgs = DOCUMENTED_PACKAGES.map((p) => `- [${npmName(p)}](${rawUrl(`packages/${p}/README.md`)}): ${summary(p)}`);
  return `# MiuJS

> A TypeScript web framework that runs without a build step on Bun, Deno, Node and Cloudflare Workers, and serves every route to AI agents over MCP and OpenAPI.

- One \`t\` schema per route gives types, validation, OpenAPI, the MCP tool schema and test helpers.
- Errors are \`MiuError\`s with a stable \`MIU_E_*\` code, a message and a \`fix\`; the \`docs\` field links to the code's section in docs/errors.md.
- Batteries are \`@miujs/*\` plugins with swappable adapters: memory or SQLite locally, Cloudflare bindings in production.
- Code must be erasable TypeScript (no enums, namespaces, decorators) and use web-standard APIs. Status: 0.1, APIs may change.

## Docs

- [Getting started](${rawUrl("docs/guide.md")}): new project, routes, schemas, errors, plugins, MCP, deploying to Cloudflare, testing
- [AGENTS.md](${rawUrl("AGENTS.md")}): rules and the core API on one screen, for coding agents changing a MiuJS app or MiuJS itself
- [README](${rawUrl("README.md")}): overview, core concepts, security defaults, roadmap and known limitations
- [Error codes](${rawUrl("docs/errors.md")}): every MIU_E_* and MIU_W_* code with its package, HTTP status, meaning and fix

## Packages

${pkgs.join("\n")}

## Optional

- [llms-full.txt](${rawUrl("llms-full.txt")}): AGENTS.md, the README, the guide and every package README in one file
- [Realtime wire protocol](${rawUrl("packages/realtime/PROTOCOL.md")}): the WebSocket frames, for clients in other languages
- [Examples](${blobUrl("examples")}): a notes API using the batteries, and a Kahoot-style quiz on realtime rooms
`;
}

/** Turns relative markdown links into GitHub links, so they still work out of context. */
export function absolutizeLinks(markdown: string, file: string): string {
  return markdown.replace(/\]\(([^)\s]+)\)/g, (whole, target: string) => {
    if (/^[a-z][a-z0-9+.-]*:/i.test(target)) return whole;
    const [path, hash] = target.split("#") as [string, string | undefined];
    const resolved = path === "" ? file : posix.normalize(posix.join(posix.dirname(file), path)).replace(/\/$/, "");
    return `](${blobUrl(resolved)}${hash !== undefined ? `#${hash}` : ""})`;
  });
}

export function llmsFullSources(): string[] {
  return ["AGENTS.md", "README.md", "docs/guide.md", ...DOCUMENTED_PACKAGES.map((p) => `packages/${p}/README.md`)].filter((p) => existsSync(join(ROOT, p)));
}

export function renderLlmsFull(): string {
  const parts = llmsFullSources().map((p) => `<!-- source: ${p} -->\n\n${absolutizeLinks(read(p), p).trim()}\n`);
  return `# MiuJS: full documentation for LLMs

Generated by scripts/build-llms.ts from the files named in each \`source\` comment. Links point at
${blobUrl("")}.

${parts.join("\n---\n\n")}`;
}

if (import.meta.main) {
  const outputs: [string, string][] = [
    ["llms.txt", renderLlmsTxt()],
    ["llms-full.txt", renderLlmsFull()],
  ];
  if (process.argv.includes("--check")) {
    const stale = outputs.filter(([p, text]) => !existsSync(join(ROOT, p)) || read(p) !== text).map(([p]) => p);
    if (stale.length) {
      console.error(`${stale.join(" and ")} out of date. Run: bun scripts/build-llms.ts`);
      process.exit(1);
    }
    console.log("llms.txt and llms-full.txt are up to date.");
  } else {
    for (const [p, text] of outputs) writeFileSync(join(ROOT, p), text);
    console.log(`Wrote llms.txt and llms-full.txt (${llmsFullSources().length} sources).`);
  }
}
